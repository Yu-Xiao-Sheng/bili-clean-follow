// 片内数字注入器（FOR-70 硬门禁）
//
// 纪律：两支 v2 影片里出现的每一个数量都必须来自真实取证会话，禁止在源码里手写。
// 取数来源 = docs/qa-report-v2.json（FOR-67 产出，B 轨真实登录态会话）。
//
//   npm run fill                                  # 默认读 ../docs/qa-report-v2.json
//   npm run fill -- --from=../docs/qa-report-v2.json
//
// 退出码非 0（都不许继续渲染）：报告不存在 / JSON 不合法 / 契约字段缺失或类型不对 /
// sum(cls.counts) != follow_total / diff.n < unfollow.done / tracks 取值非法。
// 契约与校验实现见 promo/src/numbersCore.mjs（FOR-67 冻结的那份），测试也读它。
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { BATCH_SIZE, PAGE_SIZE, deriveValues, validateReport } from "../src/numbersCore.mjs";

const ROOT = path.resolve(import.meta.dirname, "..");
const arg = (name, dflt) => {
  const hit = process.argv.slice(2).find((a) => a.startsWith("--" + name + "="));
  return hit ? hit.slice(name.length + 3) : dflt;
};

const FROM = path.resolve(ROOT, arg("from", "../docs/qa-report-v2.json"));
const OUT = path.resolve(ROOT, arg("out", "src/numbers.generated.ts"));

const fail = (msg) => {
  console.error("[fill_numbers] " + msg);
  process.exit(1);
};

if (!fs.existsSync(FROM)) {
  fail(
    "取数文件不存在：" + FROM + "\n" +
    "  片内数字必须来自 FOR-67 的真实取证报告（B 轨真实登录态会话）。\n" +
    "  报告没落地之前，两支片子不许渲染。"
  );
}

let report;
try {
  report = JSON.parse(fs.readFileSync(FROM, "utf8"));
} catch (e) {
  fail("报告不是合法 JSON：" + e.message);
}

const check = validateReport(report);
if (!check.ok) fail(check.error);

const values = deriveValues(report);
if (values.partialFetched <= 0) {
  fail("follow_total 太小，推不出「中断样本」文案（至少要 3 页才能演读全门禁）");
}

const payload = {
  filled: true,
  source: path.relative(ROOT, FROM).replace(/\\/g, "/"),
  generatedAt: new Date().toISOString(),
  reportGeneratedAt: report.generated_at,
  tracks: report.tracks,
  env: report.env,
  provenance: {
    partial_fetched: "derived: follow_total - 2 * " + PAGE_SIZE + " (B 站 relation/followings 分页 20 条/页)",
    batch: "derived: ceil(follow_total / " + BATCH_SIZE + ") (extension/classifyLlm.js BATCH_SIZE)",
  },
  values,
};

const ts = [
  "// AUTO-GENERATED by promo/tools/fill_numbers.mjs —— 不要手改。",
  "// 来源: " + payload.source + " （报告生成于 " + payload.reportGeneratedAt + "）",
  "// 手改这里等于在片子里手写数字：tests/promo/numbers_gate.test.mjs 会拦住没有报告支撑的改动。",
  "export const NUMBERS = " + JSON.stringify(payload, null, 2) + " as const;",
  "",
].join("\n");

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, ts, "utf8");

console.log("[fill_numbers] 注入完成 -> " + path.relative(ROOT, OUT));
console.log(
  "  follow_total=" + values.followTotal + "  pages=" + values.pages +
  "  partial_fetched=" + values.partialFetched + "  batch=" + values.batchCurrent + "/" + values.batchTotal
);
console.log(
  "  类目 " + values.categories.length + " 类 / 合计 " + values.categories.reduce((a, c) => a + c.n, 0) +
  " 条  diff.n=" + values.diffN + "  unfollow.done=" + values.unfollowDone
);
console.log("  取证轨道 A/B/C = " + payload.tracks.A + "/" + payload.tracks.B + "/" + payload.tracks.C);
console.log("  环境: " + payload.env.os + " / chrome " + payload.env.chrome + " / node " + payload.env.node);